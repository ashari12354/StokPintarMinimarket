-- 1. TABEL MASTER_STOK
CREATE TABLE IF NOT EXISTS public.master_stok (
    "SKU" VARCHAR(32) PRIMARY KEY,
    "Nama_Produk" VARCHAR(150) NOT NULL,
    "Kategori" VARCHAR(80) NOT NULL,
    "Harga_Beli" NUMERIC(15, 2) NOT NULL DEFAULT 0 CHECK ("Harga_Beli" >= 0),
    "Harga_Jual" NUMERIC(15, 2) NOT NULL DEFAULT 0 CHECK ("Harga_Jual" >= 0),
    "Stok_Saat_Ini" INTEGER NOT NULL DEFAULT 0 CHECK ("Stok_Saat_Ini" >= 0),
    "Batas_Minimum" INTEGER NOT NULL DEFAULT 5 CHECK ("Batas_Minimum" >= 0),
    "Lokasi_Rak" VARCHAR(50) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_master_stok_kategori ON public.master_stok ("Kategori");
CREATE INDEX IF NOT EXISTS idx_master_stok_kritis ON public.master_stok ("Stok_Saat_Ini", "Batas_Minimum");

-- 2. TABEL LOG_TRANSAKSI
CREATE TABLE IF NOT EXISTS public.log_transaksi (
    "ID_Transaksi" VARCHAR(36) PRIMARY KEY,
    "Tanggal" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "Jenis" VARCHAR(10) NOT NULL CHECK ("Jenis" IN ('Masuk', 'Keluar')),
    "SKU" VARCHAR(32) NOT NULL REFERENCES public.master_stok("SKU") ON UPDATE CASCADE ON DELETE RESTRICT,
    "Jumlah" INTEGER NOT NULL CHECK ("Jumlah" > 0),
    "Keterangan" TEXT,
    "User" VARCHAR(80) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_log_transaksi_sku ON public.log_transaksi ("SKU");
CREATE INDEX IF NOT EXISTS idx_log_transaksi_tanggal ON public.log_transaksi ("Tanggal" DESC);

-- 3. VIEW RINGKASAN_DASHBOARD (Menggunakan security_invoker = true sesuai standar keamanan Supabase Postgres 15+)
CREATE OR REPLACE VIEW public.ringkasan_dashboard
WITH (security_invoker = true) AS
SELECT
    COUNT("SKU") AS "Total_Produk",
    COALESCE(SUM("Stok_Saat_Ini"), 0) AS "Total_Unit_Stok",
    COALESCE(SUM("Stok_Saat_Ini" * "Harga_Beli"), 0) AS "Total_Nilai_Stok",
    COALESCE(SUM("Stok_Saat_Ini" * "Harga_Jual"), 0) AS "Total_Nilai_Jual",
    COUNT(CASE WHEN "Stok_Saat_Ini" <= "Batas_Minimum" THEN 1 END) AS "Jumlah_Stok_Kritis"
FROM public.master_stok;

-- 4. TABEL TODOS (Untuk tes SSR Page)
CREATE TABLE IF NOT EXISTS public.todos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. GRANT TABLE ACCESS KE DATA API & AKTIFKAN ROW LEVEL SECURITY (RLS)
GRANT SELECT, INSERT, UPDATE, DELETE ON public.master_stok TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.log_transaksi TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.todos TO anon, authenticated;
GRANT SELECT ON public.ringkasan_dashboard TO anon, authenticated;

ALTER TABLE public.master_stok ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.log_transaksi ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.todos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public access master_stok" ON public.master_stok;
CREATE POLICY "Allow public access master_stok"
    ON public.master_stok FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public access log_transaksi" ON public.log_transaksi;
CREATE POLICY "Allow public access log_transaksi"
    ON public.log_transaksi FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public access todos" ON public.todos;
CREATE POLICY "Allow public access todos"
    ON public.todos FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

